#!/usr/bin/env python3
"""Renders the board view's images from the 3D model in tools/board/.

tools/board/scene.py builds a Basys 3 in Blender from the measurements in
tools/board/measured.py; tools/board/render.py ray-traces it with every live part
off, and again with groups of parts on, and cuts each part's sprite from those.

Writes, all committed so builds never need Blender:
  src/qt/board/board.png        the board, every live part off
  src/qt/board/sprites/*.png    each part's other state (switch on, LED lit, ...)
  src/qt/BoardLayout.js         where the parts and sprites go, in 0.1 mm units

Usage:
  tools/board_render.py [--samples N] [--verify]   render (Blender 4.2 or later)
  tools/board_render.py --from DIR                 install an earlier render's output
  tools/board_render.py --check                    check the committed files agree
"""
import json
import os
import re
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BOARD = os.path.join(ROOT, 'src/qt/board')
SPRITES = os.path.join(BOARD, 'sprites')
LAYOUT = os.path.join(ROOT, 'src/qt/BoardLayout.js')
RENDER = os.path.join(ROOT, 'tools/board/render.py')
NOTICE = 'Generated by tools/board_render.py from tools/board/. Do not edit.'
SEGMENTS = ['a', 'b', 'c', 'd', 'e', 'f', 'g', 'dp']
UNITS_PER_PIXEL = 10 / 16      # 0.1 mm board units per rendered pixel (16 px/mm)


def blender():
    for candidate in (os.environ.get('BLENDER'), shutil.which('blender'),
                      '/Applications/Blender.app/Contents/MacOS/Blender'):
        if candidate and os.path.exists(candidate):
            return candidate
    sys.exit('board_render: Blender not found; install it or set BLENDER')


def layout_js(layout):
    lines = ['// ' + NOTICE,
             '// Rectangles are [x, y, width, height] in board units of 0.1 mm; a part\'s',
             '// sprite rectangle is relative to the part, a digit\'s segments to the digit.',
             '.pragma library', '']
    for key in ('width', 'height', 'switches', 'leds', 'buttons', 'done', 'display', 'digits'):
        lines.append(f'var {key} = {json.dumps(layout[key], separators=(",", ":"))}')
    return '\n'.join(lines) + '\n'


def sprite_files():
    names = [f'switch-{i}.png' for i in range(16)] + [f'led-{i}.png' for i in range(16)]
    names += [f'button-{i}.png' for i in range(5)] + ['done.png']
    names += [f'segment-{d}-{s}.png' for d in range(4) for s in SEGMENTS]
    return names


def png_size(path):
    with open(path, 'rb') as f:
        head = f.read(24)
    if len(head) < 24 or head[:8] != b'\x89PNG\r\n\x1a\n':
        raise ValueError(f'{path} is not a PNG')
    return struct.unpack('>II', head[16:24])


def check():
    try:
        check_layout()
    except (KeyError, IndexError, TypeError) as e:
        sys.exit(f'board_render: BoardLayout.js lacks an expected entry ({e!r})')


def check_layout():
    problems = []
    try:
        text = open(LAYOUT).read()
    except OSError as e:
        sys.exit(f'board_render: {e}')
    values = dict(re.findall(r'^var (\w+) = (.*)$', text, re.MULTILINE))
    try:
        layout = {k: json.loads(v) for k, v in values.items()}
    except ValueError as e:
        sys.exit(f'board_render: BoardLayout.js does not parse: {e}')
    missing = [k for k in ('width', 'height', 'switches', 'leds', 'buttons', 'done', 'display', 'digits')
               if k not in layout]
    if missing:
        sys.exit('board_render: BoardLayout.js lacks ' + ', '.join(missing))
    try:
        w, h = png_size(os.path.join(BOARD, 'board.png'))
    except (OSError, ValueError) as e:
        sys.exit(f'board_render: {e}')
    if [round(w * UNITS_PER_PIXEL), round(h * UNITS_PER_PIXEL)] != [layout['width'], layout['height']]:
        problems.append(f'board.png is {w} x {h} px, not {layout["width"]} x {layout["height"]} units')
    expected = {'switches': 16, 'leds': 16, 'buttons': 5, 'digits': 4}
    for key, count in expected.items():
        if len(layout.get(key, [])) != count:
            problems.append(f'BoardLayout.js has {len(layout.get(key, []))} {key}, not {count}')

    def sprite(name, rect):
        path = os.path.join(SPRITES, name)
        try:
            sw, sh = png_size(path)
        except (OSError, ValueError):
            problems.append(f'missing or unreadable sprite {name}')
            return
        if abs(sw * UNITS_PER_PIXEL - rect[2]) > 0.01 or abs(sh * UNITS_PER_PIXEL - rect[3]) > 0.01:
            problems.append(f'{name} is {sw} x {sh} px but placed as {rect[2]} x {rect[3]} units')

    def inside(name, rect, parent=None):
        x, y = rect[0] + (parent[0] if parent else 0), rect[1] + (parent[1] if parent else 0)
        if x < 0 or y < 0 or x + rect[2] > layout['width'] or y + rect[3] > layout['height']:
            problems.append(f'{name} lies outside the board image')
    for group, prefix in (('switches', 'switch'), ('leds', 'led'), ('buttons', 'button')):
        for i, part in enumerate(layout.get(group, [])):
            inside(f'{prefix} {i}', part['rect'])
            inside(f'{prefix} {i} sprite', part['sprite'], part['rect'])
            sprite(f'{prefix}-{i}.png', part['sprite'])
    inside('DONE LED sprite', layout['done']['sprite'])
    sprite('done.png', layout['done']['sprite'])
    inside('display', layout['display']['rect'])
    for d, digit in enumerate(layout.get('digits', [])):
        inside(f'digit {d}', digit['rect'])
        if len(digit['segments']) != len(SEGMENTS):
            problems.append(f'digit {d} has {len(digit["segments"])} segments, not 8')
            continue
        for s, seg in zip(SEGMENTS, digit['segments']):
            inside(f'digit {d} segment {s}', seg['rect'], digit['rect'])
            sprite(f'segment-{d}-{s}.png', seg['rect'])
    extra = sorted(set(os.listdir(SPRITES)) - set(sprite_files())) if os.path.isdir(SPRITES) else []
    problems += [f'unexpected sprite {name}' for name in extra]
    for p in problems:
        print('board_render:', p)
    sys.exit(1 if problems else 0)


def install(work):
    layout = json.load(open(os.path.join(work, 'layout.json')))
    os.makedirs(SPRITES, exist_ok=True)
    shutil.copyfile(os.path.join(work, 'board.png'), os.path.join(BOARD, 'board.png'))
    for name in os.listdir(SPRITES):
        os.remove(os.path.join(SPRITES, name))
    for name in sprite_files():
        shutil.copyfile(os.path.join(work, 'sprites', name), os.path.join(SPRITES, name))
    with open(LAYOUT, 'w') as f:
        f.write(layout_js(layout))
    print('board_render: wrote src/qt/board/board.png, src/qt/board/sprites/ and src/qt/BoardLayout.js')


def main():
    args = sys.argv[1:]
    if '--check' in args:
        check()
    if '--from' in args:
        install(args[args.index('--from') + 1])
        return
    samples = 256
    if '--samples' in args:
        samples = int(args[args.index('--samples') + 1])
    with tempfile.TemporaryDirectory() as work:
        cmd = [blender(), '-b', '--factory-startup', '--python', RENDER, '--', work, str(samples)]
        if '--verify' in args:
            cmd.append('--verify')
        run = subprocess.run(cmd, capture_output=True, text=True)
        for line in run.stdout.splitlines():
            if line.startswith('board_render:'):
                print(line)
        if run.returncode != 0 or not os.path.exists(os.path.join(work, 'layout.json')):
            sys.stderr.write(run.stdout[-4000:] + run.stderr[-4000:])
            sys.exit('board_render: Blender failed')
        install(work)


if __name__ == '__main__':
    main()
